import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { getConfig } from "@/lib/config";
import type { DocumentExtension } from "@/features/imports/documents";

/*
 * Where an import's uploaded files live: <UPLOADS_DIR>/imports/<import id>/<stored name>. Only
 * generated names reach the file system (a GUID and an allowed extension), and both parts are
 * checked again here, so no request value can point outside the folder.
 */

const GUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const STORED_NAME = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.[a-z]{3,4}$/;

function filePath(importId: string, storedName: string): string {
  if (!GUID.test(importId) || !STORED_NAME.test(storedName)) throw new Error("Refused a document path that was not generated by DigiDocs.");
  return path.join(getConfig().uploadsDir, "imports", importId, storedName);
}

/** Writes a new file and returns its stored name. */
export async function storeImportFile(importId: string, extension: DocumentExtension, bytes: Uint8Array): Promise<string> {
  const storedName = `${randomUUID()}.${extension}`;
  const target = filePath(importId, storedName);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, bytes, { flag: "wx" }); // never overwrites
  return storedName;
}

export async function readImportFile(importId: string, storedName: string): Promise<Buffer> {
  return readFile(filePath(importId, storedName));
}

/** Removes files whose rows are gone. Best effort: a file already missing is not an error. */
export async function removeImportFiles(importId: string, storedNames: readonly string[]): Promise<void> {
  await Promise.all(
    storedNames.map((storedName) =>
      unlink(filePath(importId, storedName)).catch((error: NodeJS.ErrnoException) => {
        if (error.code !== "ENOENT") console.error(`Could not remove uploaded file ${importId}/${storedName}:`, error.message);
      }),
    ),
  );
}
