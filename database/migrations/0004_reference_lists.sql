/*
  0004_reference_lists — the fixed lists the import and export forms choose from (module 2):
  countries, currencies, Nigerian states, free zones, units of measurement, ports, document types,
  transaction types and the documents each one requires, banks and clearing agents; and the table
  for HSE codes (filled by 0005). Fixed data: changed only by new migrations (decision log
  2026-10-08). Banks and clearing agents get their own screens in module 3.

  Left out on purpose: M_Currency's per-country duplicates and garbled symbols (one row per ISO
  code here), M_PortLoading (empty), M_Country.RegionId (no meaning in the data), the inactive
  links of Map_ParticularDocument, M_Supplier (test data), and M_WorkFlowStatus, M_KeyInfoInput,
  M_ListOfValues, which come with the Import, Export and Orion modules.

  Run against DigiDocsOPNext after 0003 (see database/README.md):
      sqlcmd -S <server> -d DigiDocsOPNext -E -b -i database/migrations/0004_reference_lists.sql

  Safe to run twice: it records itself in dbo.schema_migrations and stops if already applied.
  Never edit this file after it has been applied anywhere; add a new one instead.
  Generated from the old DigiDocs dump (Database/digidocs-09Mar26.sql); legacy_id is the old id.
*/
